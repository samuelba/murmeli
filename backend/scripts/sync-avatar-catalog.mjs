#!/usr/bin/env node
// Regenerates src/modules/kids/avatar-catalog.ts from brand/avatars/manifest.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const backendRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath =
  process.argv[2] ?? join(backendRoot, '..', 'brand', 'avatars', 'manifest.json');
const outputPath = join(backendRoot, 'src', 'modules', 'kids', 'avatar-catalog.ts');

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const list = (values) => values.map((value) => `  '${value}',`).join('\n');

const source = `// Generated by \`npm run avatars:sync\` from brand/avatars/manifest.json. Do not edit.

export const AVATAR_ANIMALS: readonly string[] = [
${list(manifest.animals.map((animal) => animal.id))}
];

export const AVATAR_ACCESSORIES: readonly string[] = [
${list(manifest.accessories.map((accessory) => accessory.id))}
];

export const AVATAR_BACKGROUNDS: readonly string[] = [
${list(manifest.backgrounds)}
];
`;

writeFileSync(outputPath, source);
console.log(`Wrote ${outputPath}`);
